#!/usr/bin/env bash
# Generate the rig's SSH identity and the config fragment that reaches it, then print
# the one line the developer has to add by hand.
#
# It never writes to ~/.ssh/config. That file grants access to production, and a
# script that edits it is a script that can break it. The `Include` is the
# developer's to paste, and to remove.
#
# Re-runnable: an existing keypair is left alone, the fragment is rewritten.

set -euo pipefail

# Declared and assigned separately: `readonly x="$(...)"` makes the command
# substitution's exit status the declaration's, which always succeeds, so `set -e`
# would not catch a failed cd.
RIG_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
readonly RIG_DIR

readonly SSH_DIR="${RIG_DIR}/ssh"
readonly KEY="${SSH_DIR}/id_ed25519"
readonly CONFIG="${SSH_DIR}/config"
readonly KNOWN_HOSTS="${SSH_DIR}/known_hosts"

readonly PRODUCTION_SSH_PORT="${PRODUCTION_SSH_PORT:-2201}"
readonly STAGING_SSH_PORT="${STAGING_SSH_PORT:-2202}"

mkdir -p "${SSH_DIR}"
chmod 0700 "${SSH_DIR}"

if [[ ! -f "${KEY}" ]]; then
	ssh-keygen -t ed25519 -N '' -C 'brama-testenv' -f "${KEY}" >/dev/null
	echo "generated ${KEY}"
fi

# The host aliases are verbose on purpose. A developer's ~/.ssh/config holds live
# production hosts, and a half-typed short name must not be able to land on one.
host_entry() {
	local alias="$1" port="$2"
	cat <<ENTRY

Host ${alias}
    HostName 127.0.0.1
    Port ${port}
    User deploy
    # IdentityFile with IdentitiesOnly: no ssh-agent required, and the developer's
    # real keys are never offered to a container.
    IdentityFile ${KEY}
    IdentitiesOnly yes
    # A known_hosts of the rig's own. The Servers get fresh host keys on every
    # rebuild, and that churn has no business in the file that pins production.
    UserKnownHostsFile ${KNOWN_HOSTS}
    StrictHostKeyChecking accept-new
ENTRY
}

{
	cat <<'HEADER'
# Generated by test/testenv/bin/ssh-setup.sh. Do not edit — re-run the script.
#
# Two containerised Servers on the loopback interface. Nothing here reaches anything
# that is not this laptop.
HEADER
	host_entry brama-testenv-production "${PRODUCTION_SSH_PORT}"
	host_entry brama-testenv-staging "${STAGING_SSH_PORT}"
} > "${CONFIG}"
chmod 0600 "${CONFIG}"

touch "${KNOWN_HOSTS}"

cat <<MESSAGE

Wrote ${CONFIG}

Add this line to the TOP of your ~/.ssh/config, then remove it when you are done
with the rig. Nothing writes to that file but you:

    Include ${CONFIG}

Once it is there:

    ssh brama-testenv-production
    ssh brama-testenv-staging
MESSAGE
